/**
 * 领域学习输入意图路由（第 3 项阶段一；前后端共用纯函数）
 * @module shared/utils/domain-learning-intent
 *
 * 答疑框不设模式、同框自动判断去向：
 * - 'tutor'：学习/答疑类输入（基于讲义引证问答，落 dl_question 历史）——默认；
 * - 'task' ：明确的任务指令（研究/整理/规划/汇总生成等"离开当前讲义的工作"），
 *            由任务会话执行（可拆子步骤、调技能/读资料、dl_* 落库）。
 *
 * 判定为可离线测试的启发式正则（2026-09-09 复盘修复口径）：
 * - 强任务词（研究/检索/规划/生成/做成/讲义合集…）直接 task；
 * - 时效检索（查最近/最新 + 资讯词）单独成强词（"查一下最近三天的新论文"型）；
 * - "整理/梳理/归纳/总结/汇总/收集/分析"为弱任务词：必须带产出型宾语
 *   （提纲/清单/报告/大纲/文档/笔记/合集…）才 task——避免把答疑里的
 *   "帮我再梳理一遍推导思路"误路由 task；
 * - 拿不准一律回 'tutor'（答疑框主职 + 不会把答疑误送任务）。
 */

export type DlIntentRoute = 'tutor' | 'task'

/** 强任务信号：动词/短语直接面向"离开讲义的工作" */
const STRONG_TASK_PATTERNS: RegExp[] = [
  /研究|调研|深挖/,
  /检索|查证|搜索资料|联网查|查一下资料/,
  /规划|计划|学习路线|学习计划/,
  /拆解|分步|拆成|细化/,
  /生成|起草|写成|做一份|写一份|做成|产出/,
  /复习提纲|讲义合集|起步研究|领域地图/,
  /对比.{0,10}(资料|文章|来源|两篇|多篇|表)/,
  // 建图/改图指令（2026-09-12：用户"追加知识点 / 补全知识体系"应走任务会话，
  // 那里才有落库口径；此前这类说法拿不准会落到答疑，只得到一段建议文字而不是真的落库）
  // ① 动词 + 结构名词（知识点/概念/节点/分支/目录/地图/体系/骨架）。
  //    宾语后跟讲义/定义/解释等内容词时是求讲解不是建图（"完善这个概念的讲义"）
  //    ——负向断言排除，避免把答疑误送进"只补结构、不产出讲义"的任务流
  /(追加|添加|新增|补充|补全|完善).{0,10}(知识点|概念|节点|分支|目录|地图|知识体系|体系|骨架)(?!的?(讲义|讲解|定义|解释|说明|推导|原理|证明|例子|示例|内容|答案))/,
  // ② 动词 + 前置/关系 + 边类尾词（"追加一条前置边""建立关系图"）
  /(追加|添加|新增|补充|补上|建立|连线).{0,8}(前置|关系)(边|链|连线|关系|图)/,
  // ③ 前置/关系 + 动作尾词（"把前置关系补上""这些前置连上"）
  /(前置|关系).{0,6}(补上|补齐|连上|连到|建立|落成|落库)/,
  // 时效检索：查/搜 + 时间词 + 资讯类宾语（"查一下最近三天有什么新论文"）
  /(查|搜)(一?下)?(最近|最新|近期|这几天|今天|本周|这周|昨天|近).{0,14}(论文|文章|资料|动态|资讯|新闻|进展|报告)/,
  // 资讯问带检索倾向词（"最近有什么新动态/进展，帮我查查"）
  /(最近|最新|近期).{0,20}(查|搜|动态|进展|新闻|资讯)/,
]

/** 弱任务信号：带"产出型宾语"（提纲/清单/报告/成文…）才判任务；
 *  "整理/梳理/归纳"等对话性动词列此（答疑里的"梳理一遍/理一理"不带宾语 → tutor） */
const WEAK_TASK_PATTERNS: RegExp[] = [
  /(总结|汇总|收集|分析|整理|梳理|归纳).{0,16}(提纲|清单|报告|大纲|表格|文档|笔记|合集|成文|多篇|对比|资料)/,
]

const NOISE = /[\s\u3000\r\n]+/g

/** 判定该输入应走答疑（tutor）还是任务执行（task） */
export function routeDlIntent(input: string): DlIntentRoute {
  const text = String(input ?? '').replace(NOISE, '')
  if (!text) return 'tutor'
  for (const re of STRONG_TASK_PATTERNS) if (re.test(text)) return 'task'
  for (const re of WEAK_TASK_PATTERNS) if (re.test(text)) return 'task'
  return 'tutor'
}
