const db = require('better-sqlite3')(process.env.HOME + '/.config/the_bot/the_bot.db', {readonly: true})
const pid = 'vp_1789956405010_2jf82v0ni'
const ep = db.prepare('SELECT id, episode_number, title, status FROM video_episodes WHERE project_id=?').all(pid)
console.log('episodes:', JSON.stringify(ep))
const epId = ep[0].id
const script = db.prepare('SELECT id, status FROM episode_scripts WHERE episode_id=?').get(epId)
console.log('script:', JSON.stringify(script))
const scenes = db.prepare('SELECT id, scene_number, location FROM scene_scripts WHERE episode_script_id=? ORDER BY scene_number').all(script.id)
console.log('scenes:', scenes.length, scenes.map(s=>s.scene_number+':'+(s.location||'')).join(' | '))
const sb = db.prepare('SELECT id, scene_script_id, shot_number, status, video_path, segment_id FROM storyboards WHERE scene_script_id IN (SELECT id FROM scene_scripts WHERE episode_script_id=?) ORDER BY shot_number').all(script.id)
console.log('storyboards:', sb.length, 'withVideo:', sb.filter(s=>s.video_path).length, 'withSegment:', sb.filter(s=>s.segment_id).length)
const segs = db.prepare('SELECT id, seq, status, shot_count, video_path FROM ep_video_segments WHERE episode_id=? ORDER BY seq').all(epId)
console.log('segments:', JSON.stringify(segs.map(s=>({seq:s.seq,status:s.status,shots:s.shot_count,video:!!s.video_path}))))
const chars = db.prepare('SELECT id, standalone_name, override_name FROM character_bindings WHERE project_id=?').all(pid)
console.log('chars:', JSON.stringify(chars))
const mains = db.prepare("SELECT asset_id, category, confirmed, length(image_path)>0 hasImg FROM asset_image WHERE asset_type='character' AND asset_id IN (SELECT id FROM character_bindings WHERE project_id=?) AND is_main=1").all(pid)
console.log('charMains:', JSON.stringify(mains))
const prov = db.prepare("SELECT id, name, template_id FROM provider_configs WHERE template_id IN ('comfyui','volcengine','bailian') OR name LIKE '%comfy%' OR name LIKE '%Comfy%'").all()
console.log('providers:', JSON.stringify(prov))
const cfg = db.prepare('SELECT config FROM video_projects WHERE id=?').get(pid)
console.log('projConfig:', cfg.config)
