const path = require('path')
const { chromium } = require('@playwright/test')
;(async () => {
  const browser = await chromium.connectOverCDP('http://127.0.0.1:9333')
  const page = browser.contexts()[0].pages().find((p) => p.url().includes('index.html'))
  console.log('hash:', await page.evaluate(() => location.hash))
  console.log('model-btn:', await page.evaluate(() => document.querySelector('.model-btn')?.textContent?.trim() || '(无)'))
  console.log('artifact:', await page.evaluate(() => !!document.querySelector('.artifact')))
  await page.fill('.input-box', '探针：测试发送')
  console.log('input value:', await page.evaluate(() => document.querySelector('.input-box')?.value))
  const disabled = await page.evaluate(() => document.querySelector('.send-btn')?.disabled)
  console.log('send disabled:', disabled)
  await page.click('.send-btn')
  await page.waitForTimeout(2500)
  const toast = await page.evaluate(() => document.querySelector('.el-message')?.textContent?.trim() || '(无提示)')
  console.log('toast:', toast)
  console.log('msg count:', await page.evaluate(() => document.querySelectorAll('.msg').length))
  await page.screenshot({ path: 'docs/screenshot/story-room-probe.png' })
  process.exit(0)
})().catch((e) => { console.error('ERR:', e.message); process.exit(1) })
